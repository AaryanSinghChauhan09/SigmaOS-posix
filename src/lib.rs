/// POSIX pathname resolution: collapse `.`, `..`, duplicate slashes;
/// preserve trailing slash semantics and root.
pub fn normalize_path(path: &str) -> Result<String, Errno> {
    if path.is_empty() {
        return Err(Errno::Inval);
    }
    let absolute = path.starts_with('/');
    let mut out: Vec<&str> = Vec::new();
    for comp in path.split('/') {
        match comp {
            "" | "." => {}
            ".." => {
                if out.pop().is_none() && !absolute {
                    // relative path escaping root is allowed syntactically
                    out.push("..");
                }
            }
            c => out.push(c),
        }
    }
    let joined = out.join("/");
    if absolute {
        Ok(format!("/{}", joined).replace("//", "/"))
    } else if joined.is_empty() {
        Ok(".".into())
    } else {
        Ok(joined)
    }
}

/// File type bits — stat(2) `st_mode` analogue.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u32)]
pub enum FileType {
    Fifo = 0o010000,
    Chr = 0o020000,
    Dir = 0o040000,
    Blk = 0o060000,
    Reg = 0o100000,
    Lnk = 0o120000,
    Sock = 0o140000,
}

impl FileType {
    pub fn from_mode(mode: u32) -> Option<Self> {
        Some(match mode & 0o170000 {
            0o010000 => FileType::Fifo,
            0o020000 => FileType::Chr,
            0o040000 => FileType::Dir,
            0o060000 => FileType::Blk,
            0o100000 => FileType::Reg,
            0o120000 => FileType::Lnk,
            0o140000 => FileType::Sock,
            _ => return None,
        })
    }
}

/// stat(2) result structure (subset of fields, layout-stable).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Stat {
    pub dev: u64,
    pub ino: u64,
    pub mode: u32,
    pub nlink: u32,
    pub uid: u32,
    pub gid: u32,
    pub size: i64,
    pub atime: i64,
    pub mtime: i64,
    pub ctime: i64,
}

impl Stat {
    pub fn file_type(&self) -> Option<FileType> {
        FileType::from_mode(self.mode)
    }
    pub fn is_dir(&self) -> bool {
        self.file_type() == Some(FileType::Dir)
    }
    pub fn permissions(&self) -> u32 {
        self.mode & 0o7777
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn errno_roundtrip() {
        for e in [Errno::Perm, Errno::NoEnt, Errno::Inval, Errno::Nospc] {
            assert_eq!(Errno::from_raw(e.raw()), e);
        }
        assert_eq!(Errno::from_raw(9999), Errno::Unknown);
    }

    #[test]
    fn errno_display() {
        assert!(Errno::NoEnt.to_string().contains("No such file"));
    }

    #[test]
    fn syscall_numbers_stable() {
        assert_eq!(Syscall::Read.number(), 0);
        assert_eq!(Syscall::Write.number(), 1);
        assert_eq!(Syscall::Openat.number(), 257);
        assert_eq!(Syscall::Read.name(), "read");
    }

    #[test]
    fn path_normalization() {
        assert_eq!(normalize_path("/a/b/../c").unwrap(), "/a/c");
        assert_eq!(normalize_path("a//b/./c").unwrap(), "a/b/c");
        assert_eq!(normalize_path("/../x").unwrap(), "/x");
        assert_eq!(normalize_path("..").unwrap(), "..");
        assert_eq!(normalize_path("").unwrap_err(), Errno::Inval);
    }

    #[test]
    fn stat_file_type_and_mode() {
        let dir = Stat {
            dev: 0, ino: 1, mode: 0o040755, nlink: 2, uid: 0, gid: 0,
            size: 4096, atime: 0, mtime: 0, ctime: 0,
        };
        assert!(dir.is_dir());
        assert_eq!(dir.permissions(), 0o755);
        let reg = Stat { mode: 0o100644, ..dir };
        assert_eq!(reg.file_type(), Some(FileType::Reg));
    }
}
